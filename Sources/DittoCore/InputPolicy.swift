import Foundation

public enum SessionKeyAction: Equatable {
    case typeNormally, accept, move(Int), history, dismiss, cancelAndPass
}

public enum InputPolicy {
    public static func key(code: Int, command: Bool = false, option: Bool = false, control: Bool = false, shift: Bool = false, hasCandidate: Bool) -> SessionKeyAction {
        if command && !option && !control && !shift && code == 37 { return .history }
        if command || option || control { return .cancelAndPass }
        switch code {
        case 53: return .dismiss
        case 48: return hasCandidate ? .accept : .cancelAndPass
        case 125: return hasCandidate ? .move(1) : .cancelAndPass
        case 126: return hasCandidate ? .move(-1) : .cancelAndPass
        case 36, 76, 115, 116, 117, 119, 121, 123, 124: return .cancelAndPass
        default: return .typeNormally
        }
    }
    public static func allowsCapture(types: Set<String>, bundleID: String, excluded: Set<String>, paused: Bool) -> Bool {
        let confidential: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
        return !paused && !excluded.contains(bundleID) && types.isDisjoint(with: confidential)
    }
}
