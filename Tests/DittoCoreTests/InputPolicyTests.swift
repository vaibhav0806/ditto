import DittoCore

func testSessionKeyPolicy() {
    expectEqual(InputPolicy.key(code: 37, hasCandidate: true), .typeNormally) // literal l
    expectEqual(InputPolicy.key(code: 1, hasCandidate: true), .typeNormally) // literal s
    expectEqual(InputPolicy.key(code: 37, command: true, hasCandidate: false), .history)
    expectEqual(InputPolicy.key(code: 48, hasCandidate: true), .accept)
    expectEqual(InputPolicy.key(code: 48, hasCandidate: false), .cancelAndPass)
    expectEqual(InputPolicy.key(code: 36, hasCandidate: true), .cancelAndPass)
    expectEqual(InputPolicy.key(code: 53, hasCandidate: false), .dismiss)
    expectEqual(InputPolicy.key(code: 125, hasCandidate: true), .move(1))
    expectEqual(InputPolicy.key(code: 123, hasCandidate: true), .cancelAndPass)
    expectEqual(InputPolicy.key(code: 0, command: true, hasCandidate: true), .cancelAndPass)
    expectEqual(InputPolicy.key(code: 0, option: true, hasCandidate: true), .cancelAndPass)
}

func testConfidentialClipboardPolicy() {
    for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"] {
        expectFalse(InputPolicy.allowsCapture(types: ["public.utf8-plain-text", marker], bundleID: "notes", excluded: [], paused: false))
    }
    expectFalse(InputPolicy.allowsCapture(types: [], bundleID: "excluded", excluded: ["excluded"], paused: false))
    expectFalse(InputPolicy.allowsCapture(types: [], bundleID: "notes", excluded: [], paused: true))
    expectTrue(InputPolicy.allowsCapture(types: ["public.utf8-plain-text"], bundleID: "notes", excluded: [], paused: false))
}
